# Умовні оператори
x = 15
if x > 0:
    print("Число додатне")
elif x == 0:
    print("Число нуль")
else:
    print("Число від'ємне")

# Булеві оператори та складна умова
age = 20
student = True
if age >= 18 and student:
    print("Повнолітній студент")

# Цикл for
for i in range(5):
    print("Цикл for:", i)

# Цикл while
count = 0
while count < 3:
    print("Цикл while:", count)
    count += 1
